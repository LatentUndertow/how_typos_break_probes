"""
Stanford Alpaca instruction-following dataset from HuggingFace.

Diverse benign instructions covering health, knowledge, math, coding, creative writing, etc.
"""

from typing import Dict, Any, Optional
from activation_robustness.datasets.hf_dataset import HFDataset
from activation_robustness.data.prompt_spec import PromptSpec
from activation_robustness.data.data_loader import DatasetMeta


class AlpacaDataset(HFDataset):
    """
    Stanford Alpaca instruction-following dataset.

    Dataset: tatsu-lab/alpaca

    52K instructions generated by text-davinci-003 covering diverse topics.
    All examples are benign instruction-following prompts.

    Schema:
    - instruction: str (task instruction)
    - input: str (optional context/input for the instruction)
    - output: str (model response)
    - text: str (formatted instruction-response pair)

    Splits:
    - train: 52,002 rows
    """

    DATASET_META = DatasetMeta(default_params={'split': 'train'}, category='benign')

    def __init__(
        self,
        split: str = "train",
        name: Optional[str] = None,
        dataset_id: Optional[str] = None,
        include_input: bool = True,
        **kwargs
    ):
        self.include_input = include_input
        super().__init__(
            repo_id="tatsu-lab/alpaca",
            split=split,
            name=name or "alpaca",
            dataset_id=dataset_id or "alpaca",
            **kwargs
        )

    def _convert_to_prompt_spec(
        self,
        example: Dict[str, Any],
        index: int
    ) -> PromptSpec:
        instruction = example.get("instruction", "")
        input_text = example.get("input", "") or ""

        if self.include_input and input_text.strip():
            content = f"{instruction}\n\n{input_text}"
        else:
            content = instruction

        messages = [
            {"role": "user", "content": content}
        ]

        labels = {
            "malicious": False,
            "has_input": bool(input_text.strip()),
        }

        prompt_id = f"{self.dataset_id}:{self.split}:{index}"

        return PromptSpec(
            prompt_id=prompt_id,
            dataset_id=self.dataset_id,
            messages=messages,
            labels=labels,
            tools=None
        )
